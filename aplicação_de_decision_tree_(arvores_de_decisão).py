import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.cluster import KMeans
from sklearn.datasets import make_blobs

"""# Geração de Dados Simulados"""

X, y = make_blobs(n_samples=300, centers=4, cluster_std=1.0,
random_state=42)
plt.scatter(X[:, 0], X[:, 1], s=50)
plt.title("Dados Simulados para Clusterização")
plt.xlabel("Componente 1")
plt.ylabel("Componente 2")
plt.grid(True)
plt.show()

"""# Aplicação do Método do Cotovelo

Esse ponto representa um equilíbrio entre a compactação dos grupos e a quantidade de clusters, coerente com os quatro centros utilizados na simulação.
"""

from sklearn.cluster import KMeans

inercia = []

for k in range(1, 10):
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    kmeans.fit(X)
    inercia.append(kmeans.inertia_)

plt.plot(range(1, 10), inercia, marker='o')
plt.title("Método do Cotovelo")
plt.xlabel("Número de Clusters")
plt.ylabel("Inércia")
plt.grid(True)
plt.show()

"""# Aplicação do K-means com k=4

O número mais adequado foi k = 4. A curva mostra uma redução expressiva da inércia até quatro grupos; depois, os ganhos tornam-se pequenos.

Neste experimento, os grupos ficaram visualmente bem separados, com concentrações compactas e pouca sobreposição. O gráfico mostra as quatro regiões ocupadas pelos dados e seus centroides. Os dois grupos da parte superior esquerda estão mais próximos entre si, mas permanecem distinguíveis.
"""

kmeans = KMeans(n_clusters=4, random_state=42, n_init=10)
kmeans.fit(X)
labels = kmeans.labels_
centros = kmeans.cluster_centers_
plt.scatter(X[:, 0], X[:, 1], c=labels, cmap='viridis')
plt.scatter(centros[:, 0], centros[:, 1], c='red', s=200, marker='X')
plt.title("Clusterização com K-means (k=4)")
plt.xlabel("Componente 1")
plt.ylabel("Componente 2")
plt.grid(True)
plt.show()

