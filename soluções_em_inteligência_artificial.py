# Célula 2 - Funções de pertinência para o tempo de espera.
def tempo_rapido(x):
    """Pertinência a tempo de espera rápido."""
    if x <= 10:
        return 1.0
    elif x <= 20:
        return (20 - x) / 10
    else:
        return 0.0

def tempo_medio(x):
    """Pertinência a tempo de espera médio."""
    if x <= 10:
        return 0.0
    elif x <= 20:
        return (x - 10) / 10
    elif x <= 30:
        return (30 - x) / 10
    else:
        return 0.0

def tempo_lento(x):
    """Pertinência a tempo de espera lento."""
    if x <= 25:
        return 0.0
    elif x <= 35:
        return (x - 25) / 10
    else:
        return 1.0

# Célula 3 - Funções de pertinência para a cordialidade.
def cordialidade_baixa(x):
    """Pertinência a cordialidade baixa."""
    if x <= 3:
        return 1.0
    elif x <= 5:
        return (5 - x) / 2
    else:
        return 0.0


def cordialidade_media(x):
    """Pertinência a cordialidade média."""
    if x <= 3:
        return 0.0
    elif x <= 5:
        return (x - 3) / 2
    elif x <= 7:
        return (7 - x) / 2
    else:
        return 0.0

def cordialidade_alta(x):
    """Pertinência a cordialidade alta."""
    if x <= 6:
        return 0.0
    elif x <= 8:
        return (x - 6) / 2
    else:
        return 1.0

# Célula 4 - Cinco grupos de regras fuzzy do roteiro.
def avaliar_atendimento(tempo, cordialidade):
    """Avalia o atendimento aplicando as regras e a média ponderada.

    1. Rápido E alta -> excelente.
    2. Rápido E média -> boa.
    3. Médio E alta -> boa.
    4. Médio E média -> regular.
    5. Demais combinações listadas no roteiro -> ruim.

    O conectivo E é calculado com min; alternativas são combinadas com max.
    A quinta regra agrupa cinco combinações explícitas no código original.
    """
    t_rapido = tempo_rapido(tempo)
    t_medio = tempo_medio(tempo)
    t_lento = tempo_lento(tempo)

    c_baixa = cordialidade_baixa(cordialidade)
    c_media = cordialidade_media(cordialidade)
    c_alta = cordialidade_alta(cordialidade)

    excelente = min(t_rapido, c_alta)
    boa = max(min(t_rapido, c_media), min(t_medio, c_alta))
    regular = min(t_medio, c_media)
    ruim = max(
        min(t_lento, c_baixa),
        min(t_lento, c_media),
        min(t_lento, c_alta),
        min(t_rapido, c_baixa),
        min(t_medio, c_baixa),
    )

    qualidade_final = (
        excelente * 9 + boa * 7 + regular * 5 + ruim * 2
    ) / max(excelente + boa + regular + ruim, 0.001)

    return {
        "excelente": excelente,
        "boa": boa,
        "regular": regular,
        "ruim": ruim,
        "qualidade_final": qualidade_final,
    }

